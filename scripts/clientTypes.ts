// Writes the clients' event types from the server's, so they can't drift apart.
// usage: bun run client-types
import { resolve } from "node:path";

import ts from "typescript";

import { EVENT_TYPES, PRIVATE_EVENT_TYPES } from "../src/gateway/events.ts";
import { STORED_RESOURCES } from "../src/ingester/sources.ts";

const root = resolve(import.meta.dir, "../");
const typesOut = resolve(root, "clients/typescript/lib/generated.ts");
const eventsOut = resolve(root, "clients/typescript/lib/events.ts");
const rubyOut = resolve(root, "clients/ruby/lib/e621stream/events.rb");

function parse(path: string): ts.SourceFile {
    return ts.createSourceFile(path, ts.sys.readFile(path)!, ts.ScriptTarget.Latest, true);
}

function declarations(source: ts.SourceFile): Map<string, ts.InterfaceDeclaration | ts.TypeAliasDeclaration> {
    const found = new Map<string, ts.InterfaceDeclaration | ts.TypeAliasDeclaration>();
    source.forEachChild((node) => {
        if (ts.isTypeAliasDeclaration(node) || ts.isInterfaceDeclaration(node)) found.set(node.name.text, node);
    });
    return found;
}

// the server's types, with E621.X written as X since the records are copied in alongside them
function serverType(source: ts.SourceFile, name: string): string {
    const node = declarations(source).get(name);
    if (!node) throw new Error(`${name} isn't in ${source.fileName}`);
    const text = node.getText(source).replaceAll("E621.", "");
    return text.startsWith("export ") ? text : `export ${text}`;
}

// every e621-openapi type the copied ones use, and the ones those use
function records(text: string): string {
    const path = Bun.resolveSync("e621-openapi/types", root).replace(/\.js$/, ".d.ts");
    const source = parse(path);
    const aliases = declarations(source);
    const included: Array<string> = [];
    const visit = (name: string): void => {
        const alias = aliases.get(name);
        if (!alias || included.includes(name)) return;
        included.push(name);
        const walk = (node: ts.Node): void => {
            if (ts.isTypeReferenceNode(node) && ts.isIdentifier(node.typeName)) visit(node.typeName.text);
            node.forEachChild(walk);
        };
        walk(alias);
    };
    for (const [, name] of text.matchAll(/\b([A-Z][A-Za-z]+)\b/g)) visit(name!);
    return [...aliases.values()].filter(alias => included.includes(alias.name.text)).map(alias => alias.getFullText(source).trim()).join("\n\n");
}

const events = parse(resolve(root, "src/gateway/events.ts"));
const filter = parse(resolve(root, "src/gateway/filter.ts"));
const snapshots = parse(resolve(root, "src/gateway/snapshots.ts"));

const snapshotTypes = declarations(snapshots).get("SnapshotTypeMap") as ts.InterfaceDeclaration;
// only what something stores, the rest of the snapshot map would always be empty
const stored = snapshotTypes.members.filter(member => ts.isPropertySignature(member) && STORED_RESOURCES.includes((member.name as ts.Identifier).text as never)).map(member => `    ${member.getText(snapshots).replaceAll("Types.", "")}`);

const ours = [
    "type IDOnly<T extends { id: number }> = Partial<Omit<T, \"id\">> & Pick<T, \"id\">;",
    `/** The \`data\` each event type is sent with. */\n${serverType(events, "EventTypeDataMap")}`,
    `/** The \`data\` each private event type is sent with. */\n${serverType(events, "PrivateEventTypeDataMap")}`,
    serverType(events, "EventContext"),
    serverType(filter, "Filter"),
    `/** What's stored for each resource \`snapshot\` can be asked for. */\nexport interface SnapshotDataMap {\n${stored.join("\n")}\n}`,
].join("\n\n");

const header = "// generated by scripts/clientTypes.ts in the E621Stream repository, don't edit by hand\n/* eslint-disable */";
await Bun.write(typesOut, `${header}\n\n${ours}\n\n// records, from the e621-openapi module's types (https://www.npmjs.com/package/e621-openapi)\n${records(ours)}\n`);
console.log(`wrote ${typesOut}`);

const tsList = (name: string, types: ReadonlyArray<string>): string => `export const ${name} = [\n${types.map(type => `    "${type}",\n`).join("")}] as const;`;
let tsEvents = await Bun.file(eventsOut).text();
for (const [name, types] of [["EVENT_TYPES", EVENT_TYPES], ["PRIVATE_EVENT_TYPES", PRIVATE_EVENT_TYPES]] as const) {
    tsEvents = tsEvents.replace(new RegExp(`export const ${name} = \\[[^\\]]*\\] as const;`), tsList(name, types));
}
await Bun.write(eventsOut, tsEvents);
console.log(`wrote ${eventsOut}`);

// wrapped to fit rubocop's line length
const words = (types: ReadonlyArray<string>, indent: string): string => {
    const lines: Array<string> = [];
    let line = "";
    for (const type of types) {
        if (line && indent.length + line.length + type.length + 1 > 118) {
            lines.push(indent + line);
            line = "";
        }
        line += line ? ` ${type}` : type;
    }
    return [...lines, indent + line].join("\n");
};
await Bun.write(rubyOut, `# frozen_string_literal: true
# typed: strict

module E621Stream
  module Events
    # Generated by scripts/clientTypes.ts in the E621Stream repository, from the server's src/gateway/events.ts.
    EVENT_TYPES = %w[
${words(EVENT_TYPES, "      ")}
    ].freeze

    # Polled with your own credentials and only sent to you. They have to be subscribed to by name, \`*\` doesn't include
    # them.
    PRIVATE_EVENT_TYPES = %w[${PRIVATE_EVENT_TYPES.join(" ")}].freeze
  end
end
`);
console.log(`wrote ${rubyOut}`);
process.exit(0);
